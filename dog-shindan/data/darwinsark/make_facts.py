# 犬種ごとに「全体よりはっきり多い行動」を選び、サイトで使う形にする
import json,math,os
H=os.path.dirname(os.path.abspath(__file__))
d=json.load(open(os.path.join(H,'breed_questions.json')));Q=d['questions']
JP={'2':'遊びたがる','4':'おもちゃ遊びが大好きな','5':'遊びにすぐ飽きる','6':'いつも何かしていたい','8':'興奮しても、すぐ落ち着く','11':'人へのあいさつがおだやか','12':'ちょっと恥ずかしがりやの','13':'にぎやかな','15':'いたずらのあと、反省した顔をする','17':'遠吠えをする','18':'「ウォーウォー」とおしゃべりする','19':'お留守番のとき鳴く','20':'鳴いておねだりする','21':'にぎやかな場所でも集中できる','22':'ほかの犬とよく遊ぶ','23':'呼ぶとすぐ来る','24':'鳥やリスを追いかけたがる','27':'うれしいと体じゅうで喜ぶ','28':'草を食べる','29':'おもちゃやおやつを埋めてかくす','41':'抱っこやハグはちょっと苦手な','42':'知らない人にもフレンドリーな','43':'飼い主の気配にすぐ気づく','45':'人が大好きな','49':'人といっしょにいたがる','50':'お客さんにはみんなにあいさつしたい','52':'おもちゃのおやつを最後まで取り出す','53':'「待て」でちゃんと待てる','54':'物を持ってくる','55':'自分を上手にコントロールできる','56':'反応がすばやい','57':'教えやすい','58':'とてもねばり強い','59':'獲物をじっと指し示す','60':'ぬれるのが苦手な','62':'食べ終わったお皿をなめ続ける','70':'水を勢いよく飲む','72':'ほかの犬におもちゃを貸してあげる','75':'ほかの犬にフレンドリーな','76':'自分が犬だとわかっている（ように見える）','81':'新しい場所にもすぐなじむ','83':'お手入れはちょっと苦手な','86':'音に敏感な','88':'動物病院はちょっと苦手な','89':'新しいものへの興味が長続きする','90':'雷がこわい','92':'カエルのように足を投げ出して寝る','96':'首をかしげる','98':'前足を組む','99':'利き足がある','100':'人の足に前足をのせる','102':'自信たっぷりの','106':'好奇心旺盛な','107':'愛情たっぷりの','108':'落ち着いている','109':'さっぱりしている'}
out={}
for b,qs in d['breeds'].items():
    def pick(r,dif,zmin):
        res=[]
        for q,v in qs.items():
            if q not in JP:continue
            p0=Q[q]['yes'];p=v['yes']
            if p0<=0 or p<p0*r or p-p0<dif:continue
            z=(p-p0)/math.sqrt(p0*(1-p0)/v['n'])
            if z<zmin:continue
            res.append((z,q,p,p0,v['n']))
        return sorted(res,reverse=True)
    res=pick(1.25,0.08,2.5)
    if len(res)<3:
        got={x[1] for x in res};res+= [x for x in pick(1.12,0.05,1.6) if x[1] not in got]
    out[b]=[[JP[q],round(p*100),round(p0*100)] for z,q,p,p0,n in res[:3]]
json.dump(out,open(os.path.join(H,'breed_facts.json'),'w'),ensure_ascii=False)
for b in ['pug','shiba','husky','frenchie','toypoodle','spitz','peke','dalmatian','iggy']:print(b,out.get(b))
print(sum(1 for v in out.values() if len(v)>=3),'犬種が3つ',sum(1 for v in out.values() if 0<len(v)<3),'犬種が1〜2つ',[b for b,v in out.items() if not v])
