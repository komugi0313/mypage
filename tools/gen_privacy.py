#!/usr/bin/env python3
"""プライバシーポリシーの本文を、PRO・ビギナー・易 EKI Pro の3つで同じ内容にそろえて書き出す。
使い方：python3 tools/gen_privacy.py [<eki-pro フォルダ>]
  → pro/privacy-pro.html・beginner/privacy.html（・<eki-pro>/privacy.html）の「1. 取得する情報」から「制定日」までを置きかえる。"""
import sys, re
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
REVISED = '2026年10月11日'
SITES = [
    dict(path=ROOT / 'pro' / 'privacy-pro.html', art='四柱推命', made='2026年8月1日', eki=False),
    dict(path=ROOT / 'beginner' / 'privacy.html', art='四柱推命', made='2026年8月1日', eki=False),
]
if len(sys.argv) > 1:
    SITES.append(dict(path=Path(sys.argv[1]) / 'privacy.html', art='易', made='2026年7月9日', eki=True))


