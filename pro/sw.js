const CACHE = 'shichu-jidou-v345';/* v345=相性モードのUI整理。(1)配置：①本人と②お相手の間に挟まっていた個人用ツール（他流派・保存・クリア・顧客カルテ注記・保存した鑑定者・五行凡例）を相性モードで非表示にし、①→②を背中合わせに（お相手リセットは②の下に既存）。(2)色分け：個人鑑定＝青／相性診断＝紫でタブを色分けし、番号バッジも①＝青（本人）／②＝紫（お相手）で対応づけ。個人モードは従来通りツール表示。表示層のみ・ロジック非改変。個人/相性でエラー0を確認。*/

/* 初回訪問時に先読みしてキャッシュするページ一式（このブランドのみ） */
